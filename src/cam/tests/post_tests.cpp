namespace {
struct Job {
    domain::Part part = test::leftSide();
    Setup setup{Face::B, {10, 20, 0}};
    MachineProfile machine = test::testProfile();
    ToolLibrary tools = test::testTools();
    Program program;
    Job() {
        auto r = generateProgram(part, setup, machine, tools);
        if (!r) throw std::logic_error(r.error().message);
        program = r.value().program;
    }
    PostInput input() const { return {program, part, setup, machine, tools}; }
};
} // namespace

TEST(CamPost, RegistryHasExactlyTheGenericPostprocessor) {
    auto reg = builtinPostprocessors();
    EXPECT_EQ(reg.ids(), std::vector<std::string>{"generic-iso"});
    const auto* p = reg.find("generic-iso");
    ASSERT_NE(p, nullptr);
    EXPECT_EQ(p->name(), "Generic ISO G-code (RS-274 style), UNVERIFIED");
    EXPECT_FALSE(p->verified());
    EXPECT_FALSE(reg.add(std::make_unique<GenericIsoPostprocessor>()));
    EXPECT_FALSE(reg.add(nullptr));
}

TEST(CamPost, HeaderAndBody) {
    Job job;
    GenericIsoPostprocessor post;
    auto out = post.generate(job.input());
    ASSERT_TRUE(out) << out.error().message;
    const auto& o = out.value();
    const std::string& t = o.text;
    EXPECT_FALSE(o.verifiedForMachine);
    EXPECT_FALSE(o.reviewWarnings.empty());
    EXPECT_EQ(t.rfind("(=====", 0), 0u);
    for (const char* s : {"GENERATED BY FURNITUREOS", "NOT VERIFIED AGAINST ANY CONTROLLER",
                          "REVIEWED AND PROVEN BY A QUALIFIED OPERATOR", "SETUP: FACE B UP",
                          "STOCK MIN CORNER AT X10.000 Y20.000 Z0.000", "STOCK: X10.000..730.000 Y20.000..580.000",
                          "TOOL T1: drill.5", "PROFILE NOT VERIFIED", "\nG21 G90 G17 G94\n", "\nG0 Z50.000\n",
                          "\nT1 M6\n", "\nS6000 M3\n", "\nG0 X356.000 Y543.000 Z50.000\n",
                          "\nG1 X356.000 Y543.000 Z5.000 F1500.0\n", "\nM5\n"})
        EXPECT_NE(t.find(s), std::string::npos) << s;
    // Header comes before the first code line.
    EXPECT_LT(t.find("QUALIFIED OPERATOR"), t.find("G21"));
    EXPECT_EQ(t.substr(t.size() - 4), "M30\n");
    for (const char* forbidden : {"G2 ", "G3 ", "G81", "G83", "G41", "G42"})
        EXPECT_EQ(t.find(forbidden), std::string::npos) << forbidden;
}

TEST(CamPost, RoundTripReproducesTheIr) {
    Job job;
    auto out = GenericIsoPostprocessor().generate(job.input());
    ASSERT_TRUE(out);
    auto rt = checkRoundTrip(job.program, out.value().text);
    ASSERT_TRUE(rt) << rt.error().message;
    EXPECT_TRUE(rt.value().matches);
    EXPECT_EQ(rt.value().parsedMotions, job.program.motions.size());

    std::string bad = out.value().text;
    const auto at = bad.find("Z5.000 F1500.0");
    bad.replace(at, 6, "Z5.500");
    auto rt2 = checkRoundTrip(job.program, bad);
    ASSERT_TRUE(rt2);
    EXPECT_FALSE(rt2.value().matches);
    ASSERT_EQ(rt2.value().differences.size(), 1u);
    EXPECT_NE(rt2.value().differences[0].find("motion #5: Z 5 in the IR but 5.5 in the text"), std::string::npos)
        << rt2.value().differences[0];
}

TEST(CamPost, ParserRejectsCodeOutsideTheSubset) {
    auto a = parseGenericIso("G21 G90\nG2 X1 Y1 Z1\nM30\n");
    ASSERT_FALSE(a);
    EXPECT_NE(a.error().message.find("Line 2"), std::string::npos);
    EXPECT_FALSE(parseGenericIso("G0 Z10\nM30\n"));            // before preamble
    EXPECT_FALSE(parseGenericIso("G21 G90\nG0 Z10\n"));        // no M30
    EXPECT_FALSE(parseGenericIso("G21 G90\nG1 X1 Y1 Z1\nM30\n")); // G1 without F
    EXPECT_FALSE(parseGenericIso("G21 G90\nM30\nG0 Z1\n"));    // after M30
    auto ok = parseGenericIso("(c)\nG21 G90 G17\nG0 Z50\nG0 X1 Y2 Z50\nG1 Z-1 F100\nM30\n");
    ASSERT_TRUE(ok) << ok.error().message;
    ASSERT_EQ(ok.value().size(), 3u);
    EXPECT_TRUE(ok.value()[0].zOnly);
    EXPECT_DOUBLE_EQ(ok.value()[2].target.x, 1); // modal X kept
    EXPECT_DOUBLE_EQ(ok.value()[2].target.z, -1);
}

TEST(CamPost, RefusesInvalidProgram) {
    Job job;
    job.program.motions[5].target.z = 3; // 2 mm too deep
    auto out = GenericIsoPostprocessor().generate(job.input());
    ASSERT_FALSE(out);
    EXPECT_EQ(out.error().code, core::ErrorCode::ConstraintViolation);
    EXPECT_NE(out.error().message.find("refuses"), std::string::npos);
    EXPECT_NE(out.error().message.find("cam.sim.too_deep"), std::string::npos);
}

TEST(CamPost, DeterministicOutput) {
    Job a, b;
    auto oa = GenericIsoPostprocessor().generate(a.input());
    auto ob = GenericIsoPostprocessor().generate(b.input());
    ASSERT_TRUE(oa && ob);
    EXPECT_EQ(oa.value().text, ob.value().text);
}

TEST(CamPost, DwellAddsDialectWarning) {
    auto part = test::panel();
    part.operations.push_back(test::op("h", domain::Hole{Face::A, 50, 60, 5, 13, false}));
    CamOptions o;
    o.dwellAtHoleBottom = 0.5;
    const cam::Setup s{Face::A, {}};
    auto g = generateProgram(part, s, test::testProfile(), test::testTools(), o);
    ASSERT_TRUE(g);
    const auto tools = test::testTools();
    const auto machine = test::testProfile();
    auto out = GenericIsoPostprocessor().generate({g.value().program, part, s, machine, tools});
    ASSERT_TRUE(out) << out.error().message;
    EXPECT_NE(out.value().text.find("\nG4 P0.500\n"), std::string::npos);
    bool warned = false;
    for (const auto& w : out.value().reviewWarnings) warned = warned || w.find("milliseconds") != std::string::npos;
    EXPECT_TRUE(warned);
    auto rt = checkRoundTrip(g.value().program, out.value().text);
    ASSERT_TRUE(rt);
    EXPECT_TRUE(rt.value().matches);
}
