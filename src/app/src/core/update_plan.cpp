std::string s(const QString& q) { return q.toStdString(); }

QString native(const QString& path) { return QDir::toNativeSeparators(QDir::cleanPath(path)); }

QString uniqueSibling(const QDir& parent, const QString& base) {
    QString name = base;
    for (int n = 2; parent.exists(name); ++n) name = base + QLatin1Char('-') + QString::number(n);
    return parent.filePath(name);
}

/// Script prologue: variables and the wait for the application process to exit.
QStringList prologue(const QList<QPair<QString, QString>>& vars, qint64 pid) {
    QStringList l;
    l << QStringLiteral("@echo off")
      << QStringLiteral("rem FurnitureOS updater script, generated by the application. It runs after")
      << QStringLiteral("rem FurnitureOS has exited and may be deleted afterwards.")
      << QStringLiteral("setlocal EnableExtensions DisableDelayedExpansion")
      << QStringLiteral("chcp 65001 >nul")
      << QStringLiteral("set \"FOS_PID=%1\"").arg(pid);
    for (const auto& [name, value] : vars) l << QStringLiteral("set \"%1=%2\"").arg(name, cmdEscape(value));
    // ping is the sleep: `timeout` fails without a console.
    l << QStringLiteral("set /a FOS_WAIT=0")
      << QStringLiteral(":wait_exit")
      << QStringLiteral("tasklist /FI \"PID eq %FOS_PID%\" /NH 2>nul | find \" %FOS_PID% \" >nul")
      << QStringLiteral("if errorlevel 1 goto exited")
      << QStringLiteral("set /a FOS_WAIT+=1")
      << QStringLiteral("if %FOS_WAIT% geq 120 goto fail_wait")
      << QStringLiteral("ping -n 2 127.0.0.1 >nul")
      << QStringLiteral("goto wait_exit")
      << QStringLiteral(":fail_wait")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed FurnitureOS did not exit within 120 seconds; nothing was changed.")
      << QStringLiteral("exit /b 1")
      << QStringLiteral(":exited");
    return l;
}

QString finish(const QStringList& lines) { return lines.join(QStringLiteral("\r\n")) + QStringLiteral("\r\n"); }

