InstallKind detectInstallKind(const QString& appDir, bool isWindows) {
    if (!isWindows) return InstallKind::Unsupported;
    return QFileInfo::exists(QDir(appDir).filePath(QLatin1String(kInstallerMarker))) ? InstallKind::WindowsInstalled
                                                                                     : InstallKind::WindowsPortable;
}

UpdateChoice chooseUpdate(InstallKind kind, const UpdateManifest& manifest) {
    switch (kind) {
    case InstallKind::WindowsInstalled:
        if (const UpdateAsset* a = manifest.asset(kAssetWindowsSetup)) return {UpdateMethod::RunInstaller, a};
        break;
    case InstallKind::WindowsPortable:
        if (const UpdateAsset* a = manifest.asset(kAssetWindowsZip)) return {UpdateMethod::SwapPortable, a};
        break;
    case InstallKind::Unsupported: break;
    }
    return {UpdateMethod::ManualOnly, nullptr};
}

core::Result<PortableSwapPlan> planPortableSwap(const QString& appDir, const QString& exePath, const SemVer& newVersion) {
    const QFileInfo app(QDir::cleanPath(appDir));
    if (!app.isAbsolute() || !app.isDir())
        return makeError(ErrorCode::InvalidArgument, "The application folder " + s(appDir) + " is not an existing absolute folder.");
    QDir parent = app.dir();
    if (app.fileName().isEmpty() || parent.absolutePath() == app.absoluteFilePath())
        return makeError(ErrorCode::Unsupported, "FurnitureOS runs from the root of a drive (" + s(appDir) +
                                                     "); a portable update needs it to be in its own folder.");
    PortableSwapPlan plan;
    plan.appDir = app.absoluteFilePath();
    plan.exeRelative = QDir(plan.appDir).relativeFilePath(QFileInfo(exePath).absoluteFilePath());
    if (plan.exeRelative.startsWith(QLatin1String("..")) || QFileInfo(plan.exeRelative).isAbsolute())
        return makeError(ErrorCode::InvalidArgument, "The executable " + s(exePath) + " is not inside " + s(appDir) + ".");
    const QString base = app.fileName();
    plan.stagingDir = uniqueSibling(parent, base + QStringLiteral(".update-") + QString::fromStdString(newVersion.toString()));
    plan.backupDir = uniqueSibling(parent, base + QStringLiteral(".old"));
    return plan;
}

core::Result<QString> locateStagedRoot(const QString& stagingDir, const QString& exeRelative) {
    const QDir staging(stagingDir);
    if (QFileInfo(staging.filePath(exeRelative)).isFile()) return staging.absolutePath();
    const QFileInfoList entries = staging.entryInfoList(QDir::AllEntries | QDir::NoDotAndDotDot | QDir::Hidden);
    if (entries.size() == 1 && entries.front().isDir() &&
        QFileInfo(QDir(entries.front().absoluteFilePath()).filePath(exeRelative)).isFile())
        return entries.front().absoluteFilePath();
    return makeError(ErrorCode::CorruptData, "The update archive does not contain " + s(exeRelative) +
                                                 " (at its top or in a single top-level folder); it is not a FurnitureOS "
                                                 "portable package and was not installed.");
}

QString cmdEscape(const QString& value) {
    QString v = value;
    v.replace(QLatin1Char('%'), QStringLiteral("%%"));
    return v;
}

QString portableSwapScript(const PortableSwapPlan& plan, const QString& stagedRoot, qint64 pid,
                           const QString& newVersion, const QString& resultFile) {
    const bool separateStaging = QDir::cleanPath(stagedRoot) != QDir::cleanPath(plan.stagingDir);
    QStringList l = prologue({{QStringLiteral("FOS_APP"), native(plan.appDir)},
                              {QStringLiteral("FOS_STAGED"), native(stagedRoot)},
                              {QStringLiteral("FOS_STAGING"), native(plan.stagingDir)},
                              {QStringLiteral("FOS_BACKUP"), native(plan.backupDir)},
                              {QStringLiteral("FOS_EXE"), native(plan.exeRelative)},
                              {QStringLiteral("FOS_VERSION"), newVersion},
                              {QStringLiteral("FOS_RESULT"), native(resultFile)}},
                             pid);
    l << QStringLiteral("if exist \"%FOS_BACKUP%\" goto fail_precheck")
      << QStringLiteral("if not exist \"%FOS_STAGED%\\%FOS_EXE%\" goto fail_precheck")
      // Step 1: current folder -> backup (a rename; retried while files are still locked).
      << QStringLiteral("set /a FOS_TRY=0")
      << QStringLiteral(":move_old")
      << QStringLiteral("move \"%FOS_APP%\" \"%FOS_BACKUP%\" >nul 2>&1")
      << QStringLiteral("if not errorlevel 1 goto move_new")
      << QStringLiteral("set /a FOS_TRY+=1")
      << QStringLiteral("if %FOS_TRY% geq 30 goto fail_locked")
      << QStringLiteral("ping -n 2 127.0.0.1 >nul")
      << QStringLiteral("goto move_old")
      // Step 2: staged folder -> application folder; on failure, roll back step 1.
      << QStringLiteral(":move_new")
      << QStringLiteral("move \"%FOS_STAGED%\" \"%FOS_APP%\" >nul 2>&1")
      << QStringLiteral("if not errorlevel 1 goto swapped")
      << QStringLiteral("move \"%FOS_BACKUP%\" \"%FOS_APP%\" >nul 2>&1")
      << QStringLiteral("if errorlevel 1 goto fail_rollback")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed The new version could not be moved into place; the previous "
                        "version was restored.")
      << QStringLiteral("goto relaunch_old")
      << QStringLiteral(":swapped")
      << QStringLiteral(">\"%FOS_RESULT%\" echo ok %FOS_VERSION%")
      << QStringLiteral("start \"\" /D \"%FOS_APP%\" \"%FOS_APP%\\%FOS_EXE%\"")
      << QStringLiteral("rd /s /q \"%FOS_BACKUP%\" >nul 2>&1");
    if (separateStaging) l << QStringLiteral("rd /s /q \"%FOS_STAGING%\" >nul 2>&1");
    l << QStringLiteral("exit /b 0")
      << QStringLiteral(":fail_precheck")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed The staged update or the backup folder name was not as "
                        "expected; nothing was changed.")
      << QStringLiteral("goto relaunch_old")
      << QStringLiteral(":fail_locked")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed The application folder stayed in use for 30 seconds - close "
                        "programs or windows using it and try again; nothing was changed.")
      << QStringLiteral("goto relaunch_old")
      << QStringLiteral(":fail_rollback")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed The update could not be moved into place and the previous "
                        "version could not be restored automatically: rename \"%FOS_BACKUP%\" back to \"%FOS_APP%\".")
      << QStringLiteral("exit /b 2")
      << QStringLiteral(":relaunch_old")
      << QStringLiteral("rd /s /q \"%FOS_STAGING%\" >nul 2>&1")
      << QStringLiteral("start \"\" /D \"%FOS_APP%\" \"%FOS_APP%\\%FOS_EXE%\"")
      << QStringLiteral("exit /b 1");
    return finish(l);
}

QString installerScript(const QString& setupExe, const QString& exePath, qint64 pid, const QString& newVersion,
                        const QString& resultFile) {
    QStringList l = prologue({{QStringLiteral("FOS_SETUP"), native(setupExe)},
                              {QStringLiteral("FOS_EXE_PATH"), native(exePath)},
                              {QStringLiteral("FOS_EXE_DIR"), native(QFileInfo(exePath).absolutePath())},
                              {QStringLiteral("FOS_VERSION"), newVersion},
                              {QStringLiteral("FOS_RESULT"), native(resultFile)}},
                             pid);
    l << QStringLiteral("\"%FOS_SETUP%\" %1").arg(QLatin1String(kInstallerSilentArgs))
      << QStringLiteral("set \"FOS_CODE=%errorlevel%\"")
      << QStringLiteral("if not \"%FOS_CODE%\"==\"0\" goto fail_setup")
      << QStringLiteral(">\"%FOS_RESULT%\" echo ok %FOS_VERSION%")
      << QStringLiteral("del /q \"%FOS_SETUP%\" >nul 2>&1")
      << QStringLiteral("start \"\" /D \"%FOS_EXE_DIR%\" \"%FOS_EXE_PATH%\"")
      << QStringLiteral("exit /b 0")
      << QStringLiteral(":fail_setup")
      << QStringLiteral(">\"%FOS_RESULT%\" echo failed The installer ended with exit code %FOS_CODE%; the installed "
                        "version was left as it was by the installer.")
      << QStringLiteral("start \"\" /D \"%FOS_EXE_DIR%\" \"%FOS_EXE_PATH%\"")
      << QStringLiteral("exit /b 1");
    return finish(l);
}

std::optional<UpdateOutcome> parseUpdateOutcome(const QString& text) {
    const QString t = text.trimmed();
    if (t.startsWith(QLatin1String("ok "))) return UpdateOutcome{true, t.mid(3).trimmed()};
    if (t.startsWith(QLatin1String("failed "))) return UpdateOutcome{false, t.mid(7).trimmed()};
    return std::nullopt;
}

QString updateConsentKey(UpdateConsent consent) {
    switch (consent) {
    case UpdateConsent::Allowed: return QStringLiteral("yes");
    case UpdateConsent::Declined: return QStringLiteral("no");
    case UpdateConsent::NotAsked: break;
    }
    return QStringLiteral("ask");
}

UpdateConsent updateConsentFromKey(const QString& key) {
    if (key == QLatin1String("yes")) return UpdateConsent::Allowed;
    if (key == QLatin1String("no")) return UpdateConsent::Declined;
    return UpdateConsent::NotAsked;
}

