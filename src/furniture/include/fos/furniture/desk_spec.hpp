#pragma once
/// \file
/// Panel desks and tables (README "Desks and tables"): a construction VARIANT of a
/// CabinetDefinition (CabinetDefinition::desk), like the appliance gap. The overall size comes
/// from the standard graph parameters `width` (x), `height` (z, floor to top surface) and
/// `depth` (y, front edge of the top at y = 0); every panel is `thickness` thick (carcass
/// material). All lengths mm. Every default below is a GENERIC value / rule of thumb, not
/// taken from a standard or a manufacturer.
#include "fos/domain/hardware.hpp"

#include <optional>
#include <string_view>

namespace fos::furniture {

/// How the top is carried.
///  * Panels: two full-depth end panels under the top (joined to it with
///    ConstructionOptions::topFastener) and an optional modesty panel between them (joined to
///    the ends with ConstructionOptions::dividerFastener).
///  * Legs: four screw-on legs (generic hardware, DeskSpec::leg) under the corners of the top;
///    their mounting-plate pilot holes are drilled into the underside of the top.
enum class DeskSupport { Panels, Legs };
/// Side of the under-desk drawer pedestal, seen from the front.
enum class DeskPedestalSide { Left, Right };

const char* toString(DeskSupport) noexcept;
const char* toString(DeskPedestalSide) noexcept;
std::optional<DeskSupport> deskSupportFromString(std::string_view text) noexcept;
std::optional<DeskPedestalSide> deskPedestalSideFromString(std::string_view text) noexcept;

/// Catalogue id of the generic leg (genericLegDefinition()).
inline constexpr const char* kGenericLegId = "hw.leg_generic";

/// Parameter keys of a leg definition (HardwareKind::Leg), mm. Required: plate_size,
/// plate_hole_spacing, plate_hole_diameter, plate_hole_depth. Optional: height_min /
/// height_max (range of leg lengths; a desk outside it gets furniture.desk.leg_height).
namespace leg_keys {
inline constexpr const char* kPlateSize = "plate_size";                 ///< Square plate edge length.
inline constexpr const char* kPlateHoleSpacing = "plate_hole_spacing";  ///< 4 holes on a square of this edge.
inline constexpr const char* kPlateHoleDiameter = "plate_hole_diameter";
inline constexpr const char* kPlateHoleDepth = "plate_hole_depth";
inline constexpr const char* kHeightMin = "height_min";
inline constexpr const char* kHeightMax = "height_max";
} // namespace leg_keys

/// GENERIC table leg with a square mounting plate, cut to length: id kGenericLegId, kind Leg,
/// plate 80 mm, 4 pilot holes 4 x 10 mm on a 60 mm square, length 400..1100 mm. Typical trade
/// values, unverified (dimensionsVerified = false, no manufacturer). The hardware module's
/// built-in catalogue does not contain it; project::commands::addItem adds it to the project
/// library when a desk with legs is inserted (requiredGenericHardware()).
domain::HardwareDefinition genericLegDefinition();

/// Rounded cable slot through the top (a Rectangle cut-out whose corner radius is half its
/// width), centred on x = width / 2 + centerOffset.
struct DeskCableCutout {
    double length = 300.0;       ///< Along x, mm (> width).
    double width = 60.0;         ///< Along y, mm (> 0).
    double rearDistance = 20.0;  ///< Rear edge of the top to the slot, mm (> 0).
    double centerOffset = 0.0;   ///< Slot centre right of the desk centre, mm.
    bool operator==(const DeskCableCutout&) const = default;
};

/// Under-desk drawer pedestal (Panels only): a templates::drawerUnitWithBoxes() cabinet
/// generated by the ordinary generator (on feet, full top, grooved back, drawer boxes on
/// ball-bearing slides) standing on the floor against the inner face of one end panel, as tall
/// as the clear height under the top and as deep as the space in front of the modesty panel.
/// Its parts are `<desk>/pedestal/<slot>`; it is free-standing (no fitting joins it to the desk).
struct DeskPedestal {
    DeskPedestalSide side = DeskPedestalSide::Right;
    double width = 400.0; ///< mm, kDeskMinPedestalWidth..(clear width between the ends).
    int drawers = 3;      ///< Equal drawer fronts, 1..kDeskMaxPedestalDrawers.
    bool operator==(const DeskPedestal&) const = default;
};

struct DeskSpec {
    DeskSupport support = DeskSupport::Panels;
    /// Radius of the two FRONT corners of the top (RoundedCorners contour on L1/W1 and L1/W2),
    /// mm; 0 = sharp. A user contour override on slot `top` replaces it.
    double frontCornerRadius = 0.0;
    /// Panels only: modesty panel between the ends under the top.
    bool modestyPanel = true;
    double modestySetback = 100.0; ///< Rear edge of the top to the rear face of the modesty panel, mm (>= 0).
    double modestyHeight = 350.0;  ///< Down from the underside of the top, mm (> 0).
    std::optional<DeskCableCutout> cableCutout;
    std::optional<DeskPedestal> pedestal; ///< Panels only.
    /// Legs only: leg definition (kind Leg, leg_keys) and the distance of each leg axis from
    /// the two edges of the top at its corner, mm.
    domain::HardwareId leg{kGenericLegId};
    double legInset = 70.0;
    bool operator==(const DeskSpec&) const = default;
};

/// Hard size limits of desks and tables (errors), mm. GENERIC plausibility limits.
inline constexpr double kDeskMinWidth = 600.0, kDeskMaxWidth = 3000.0;
inline constexpr double kDeskMinDepth = 400.0, kDeskMaxDepth = 1200.0;
inline constexpr double kDeskMinHeight = 500.0, kDeskMaxHeight = 1200.0;
inline constexpr double kDeskMinPedestalWidth = 250.0;
inline constexpr int kDeskMaxPedestalDrawers = 6;
/// Knee clearance RULE OF THUMB (warning furniture.desk.knee_clearance): at least 600 mm clear
/// height under the top and 600 mm clear width between the supports (end panels, pedestal,
/// leg plates) for a seated person. A heuristic, not an ergonomic standard.
inline constexpr double kDeskKneeClearance = 600.0;

} // namespace fos::furniture
